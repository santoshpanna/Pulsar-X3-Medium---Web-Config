export const FIGLET_ROWS = 6;

/** The rows of `text` in block letters. Unknown characters render as '?'. */
export function figlet(text: string): string[] {
  const glyphs = Array.from(text.toUpperCase(), (ch) => GLYPHS[ch] ?? GLYPHS['?']);
  const rows: string[] = [];
  for (let r = 0; r < FIGLET_ROWS; r++) {
    rows.push(glyphs.map((g) => {
      const w = Math.max(...g.map((l) => l.length));
      return g[r].padEnd(w, ' ');
    }).join(''));
  }
  return rows;
}
